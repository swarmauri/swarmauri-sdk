from abc import ABC, abstractmethod
from datetime import datetime
from typing import Any

from swarmauri_core.documents.IDocument import IDocument


class IExperimentDocument(IDocument, ABC):
    """
    Interface for an Experiment Document, extending the general IDocument
    interface
    with additional properties and methods specific to experimental data.
    """

    @property
    @abstractmethod
    def parameters(self) -> dict[str, Any]:
        """
        Get the parameters used in the experiment.
        """

    @parameters.setter
    @abstractmethod
    def parameters(self, value: dict[str, Any]) -> None:
        """
        Set the parameters used in the experiment.
        """

    @property
    @abstractmethod
    def results(self) -> dict[str, Any]:
        """
        Get the results obtained from the experiment.
        """

    @results.setter
    @abstractmethod
    def results(self, value: dict[str, Any]) -> None:
        """
        Set the results obtained from the experiment.
        """

    @property
    @abstractmethod
    def instruction(self) -> str:
        """
        An instructional or descriptive text about what the experiment aims to
        achieve or how.
        """

    @instruction.setter
    @abstractmethod
    def instruction(self, value: str) -> None:
        pass

    @property
    @abstractmethod
    def feature_set(self) -> list[Any]:
        """
        Description of the set of features or data used in the experiment.
        """

    @feature_set.setter
    @abstractmethod
    def feature_set(self, value: list[Any]) -> None:
        pass

    @property
    @abstractmethod
    def version(self) -> str:
        """
        The version of the experiment, useful for tracking iterations and
        changes over time.
        """

    @version.setter
    @abstractmethod
    def version(self, value: str) -> None:
        pass

    @property
    @abstractmethod
    def artifacts(self) -> list[str]:
        """
        A list of paths or identifiers for any artifacts generated by the
        experiment,
        such as models, charts, or data dumps.
        """

    @artifacts.setter
    @abstractmethod
    def artifacts(self, value: list[str]) -> None:
        pass

    @property
    @abstractmethod
    def datetime_created(self) -> datetime:
        """
        Timestamp marking when the experiment was initiated or created.
        """

    @datetime_created.setter
    @abstractmethod
    def datetime_created(self, value: datetime) -> None:
        pass

    @property
    @abstractmethod
    def datetime_completed(self) -> datetime | None:
        """
        Timestamp of when the experiment was completed. None if the experiment
        is still running.
        """

    @datetime_completed.setter
    @abstractmethod
    def datetime_completed(self, value: datetime | None) -> None:
        pass
